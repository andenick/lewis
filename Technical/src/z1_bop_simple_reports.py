def generate_all_z1_bop_simple_reports(data: Dict, metadata: Dict, analysis_results: Dict, output_dir: str) -> Dict[str, str]:
    """Generate all simplified Z.1/BOP reports."""

    generator = Z1BOPSimplifiedReports()
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    reports = {}

    # Generate reports
    report_configs = [
        ("comprehensive_historical", "comprehensive_historical_analysis.txt", generator.generate_comprehensive_historical_report),
        ("debt_dynamics", "debt_dynamics_analysis.txt", generator.generate_debt_dynamics_report),
        ("executive_summary", "executive_summary.txt", generator.generate_executive_summary)
    ]

    for report_type, filename, generate_func in report_configs:
        try:
            content = generate_func(data, metadata, analysis_results)
            report_path = output_path / filename

            with open(report_path, 'w', encoding='utf-8') as f:
                f.write(content)

            reports[report_type] = str(report_path)
            print(f"Generated {report_type} report: {report_path}")

        except Exception as e:
            print(f"Error generating {report_type} report: {e}")
            reports[report_type] = None

    return reports

